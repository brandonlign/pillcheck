"""Download the UI asset packs PillCheck bundles, so the app keeps working offline.

- Lucide icons (ISC license, https://lucide.dev) at a pinned version
  -> public/icons.js (inner SVG markup keyed by icon name)

Usage: python scripts/fetch_ui_assets.py
"""
import json, re, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LUCIDE = "1.61.0"

ICONS = [
    "house", "pill", "scan-line", "camera", "chart-no-axes-column", "settings", "plus", "chevron-right",
    "chevron-left", "check", "x", "sun", "sunrise", "sunset", "moon", "search", "image-up", "triangle-alert",
    "info", "volume-2", "download", "upload", "user-plus", "users", "flame", "shield-check", "printer",
    "calendar-days", "sparkles", "circle-help", "trash-2", "sun-moon", "a-large-small", "languages",
    "lock", "wifi-off", "clock", "grid-3x3", "refresh-cw", "list-checks", "heart-pulse", "pencil",
]


def get(url):
    with urllib.request.urlopen(url, timeout=30) as r:
        return r.read()


def main():
    icons = {}
    for name in ICONS:
        svg = get(f"https://unpkg.com/lucide-static@{LUCIDE}/icons/{name}.svg").decode()
        inner = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
        icons[name] = re.sub(r"\s+", " ", inner).strip()
    out = "// Generated by scripts/fetch_ui_assets.py from Lucide " + LUCIDE + " (ISC license, https://lucide.dev).\n"
    out += "export const lucide = " + json.dumps(icons, indent=1) + ";\n"
    (ROOT / "public/icons.js").write_text(out, encoding="utf-8")
    print("icons", len(icons))



if __name__ == "__main__":
    main()
